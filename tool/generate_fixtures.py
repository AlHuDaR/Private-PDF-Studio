"""Generate synthetic, redistributable fixtures; no real user PDFs are used.
Run in a throwaway venv with:
pip install pypdf==6.2.0 reportlab==4.4.4 arabic-reshaper==3.0.0 python-bidi==0.6.7
"""
import base64
from io import BytesIO
from pathlib import Path
import arabic_reshaper
from bidi.algorithm import get_display
from pypdf import PdfReader, PdfWriter
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

root = Path(__file__).resolve().parents[1]
fixtures = root / 'test/fixtures'
fixtures.mkdir(exist_ok=True)
writer = PdfWriter()
for width in [200, 300, 400]:
    writer.add_blank_page(width=width, height=500)
with (fixtures / 'valid.pdf').open('wb') as out:
    writer.write(out)
many = PdfWriter()
for _ in range(501):
    many.add_blank_page(width=100, height=100)
with (fixtures / 'too-many-pages.pdf').open('wb') as out:
    many.write(out)
writer = PdfWriter(clone_from=fixtures / 'valid.pdf')
writer.pages[0].rotate(90)
with (fixtures / 'rotated.pdf').open('wb') as out:
    writer.write(out)
for name, user in [('encrypted.pdf', 'test-password'), ('empty-password.pdf', '')]:
    writer = PdfWriter(clone_from=fixtures / 'valid.pdf')
    writer.encrypt(user, 'fixture-owner-password', algorithm='RC4-128')
    with (fixtures / name).open('wb') as out:
        writer.write(out)
pdfmetrics.registerFont(TTFont('NotoArabic', str(root / 'assets/fonts/NotoSansArabic-Regular.ttf')))
buffer = BytesIO()
c = canvas.Canvas(buffer, pagesize=(350, 500), invariant=1)
c.setTitle('اختبار عربي')
c.setFont('NotoArabic', 20)
c.drawRightString(320, 440, get_display(arabic_reshaper.reshape('مرحبا بالعالم')))
c.showPage()
c.save()
(fixtures / 'arabic.pdf').write_bytes(buffer.getvalue())
(fixtures / 'malformed.pdf').write_bytes(b'%PDF-1.7\nnot a document\n%%EOF\n')
# Test-only data constants allow exactly the same fixtures to run on native and
# browser test runners without adding test files to the shipped app's assets.
lines = ['// Generated by tool/generate_fixtures.py. Synthetic test data only.',
         "import 'dart:convert';", "import 'dart:typed_data';", '',
         'Uint8List fixture(String name) => base64Decode(_data[name]!);', '',
         'const _data = <String, String>{']
for path in sorted(fixtures.glob('*.pdf')):
    data = base64.b64encode(path.read_bytes()).decode('ascii')
    lines.append("  '" + path.name + "':")
    lines.extend("      '" + data[i:i+100] + "'" for i in range(0, len(data), 100))
    lines[-1] += ','
lines.append('};')
(fixtures / 'fixtures.dart').write_text('\n'.join(lines) + '\n')
print('Generated seven synthetic PDF fixtures and browser-compatible Dart data')
